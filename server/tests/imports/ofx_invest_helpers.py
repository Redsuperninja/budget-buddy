def brokerage(body=None, acct="987654321", cur="USD", seclist=SECLIST_SGML) -> str:
    """A brokerage statement in SGML shape. ``body`` replaces the position and transaction lists."""
    inner = body if body is not None else TRADES + HOLDINGS
    return (
        "<OFX><SIGNONMSGSRSV1><SONRS><STATUS><CODE>0<SEVERITY>INFO</STATUS><DTSERVER>20260110"
        "</SONRS></SIGNONMSGSRSV1>"
        f"<INVSTMTMSGSRSV1><INVSTMTTRNRS><TRNUID>1<INVSTMTRS><DTASOF>20260110120000<CURDEF>{cur}"
        f"<INVACCTFROM><BROKERID>fake.example<ACCTID>{acct}</INVACCTFROM>{inner}"
        f"</INVSTMTRS></INVSTMTTRNRS></INVSTMTMSGSRSV1>{seclist}</OFX>\r\n"
    )


